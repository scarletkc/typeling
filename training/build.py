"""
Builds word_predictor/en.bin: fetch corpora -> clean -> hold out dev/test splits -> count a Kneser-Ney trigram model
-> prune and quantize -> export.

    uv run training/build.py fetch     # download and clean corpora into data/corpus/ (finished sources are skipped)
    uv run training/build.py model     # count data/corpus/*.train.jsonl and export en.bin
    uv run training/build.py           # both steps

Corpora (permissive licenses only; attributions in NOTICE):
    fineweb   HuggingFaceFW/fineweb   ODC-By 1.0   writing: 42 evenly spaced row groups of the first sample-10BT file
    soda      allenai/soda            CC BY 4.0    everyday dialogue generated by InstructGPT: every 9th training dialogue
    wildchat  allenai/WildChat-1M     ODC-By 1.0   real user-typed text: English user turns that look human-typed
                                                   (the first 7.5M training words, about 70% of the dataset)
    oasst2    OpenAssistant/oasst2    Apache-2.0   real user-typed text: English user turns that look human-typed
    irc       common-pile/ubuntu_irc_filtered      Public Domain   informal internet chat: Ubuntu IRC messages
                                                   (non-technical-looking ones, 1.5M words from each of the 3 files)
About 1% of each source is held out as the dev split and 1% as the test split, by content hash,
so duplicate texts always land in the same split.
"""

