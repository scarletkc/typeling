def load_dictionary():
    """Lowercased union of the American, British and Canadian speller word lists."""
    import urllib.request

    words = set()
    for name in SPELL_LISTS:
        path = ROOT / "data" / "spell" / f"{name}.txt"
        if not path.exists():
            path.parent.mkdir(parents=True, exist_ok=True)
