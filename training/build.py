def _deletes(word, k):
    out = frontier = {word}
    for _ in range(k):
        frontier = {w[:i] + w[i + 1:] for w in frontier for i in range(len(w))}
        out = out | frontier
    return out


def _osa(a, b):
    """Optimal string alignment distance: insertions, deletions, substitutions and adjacent transpositions."""
    prev2, prev = None, list(range(len(b) + 1))
    for i in range(1, len(a) + 1):
        cur = [i] + [0] * len(b)
        for j in range(1, len(b) + 1):
            cur[j] = min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] != b[j - 1]))
            if i > 1 and j > 1 and a[i - 1] == b[j - 2] and a[i - 2] == b[j - 1]:
                cur[j] = min(cur[j], prev2[j - 2] + 1)
        prev2, prev = prev, cur
    return prev[-1]


def misspellings(words, counts, cased, dictionary):
    """Ids of vocabulary words that are likely misspellings: not in the dictionary or SLANG, usually written in
    lowercase (capitalized words are mostly names), and one edit (two for words of 8+ letters) away from a
    dictionary word that is at least MISSPELL_RATIO times as common. They stay in the model as context but are
    never suggested. Candidates are found with symmetric deletes and checked with _osa."""
    valid = [w in dictionary or w in SLANG for w in words]
    index = {}
    for i, w in enumerate(words):
        if valid[i]:
            for d in _deletes(w, 2):
                index.setdefault(d, []).append(i)
    out = []
    for i, w in enumerate(words):
        if valid[i] or i in cased:
            continue
        k = 2 if len(w) >= 8 else 1
        limit = MISSPELL_RATIO * counts[w]
        if any(counts[words[j]] >= limit and _osa(w, words[j]) <= k
               for d in _deletes(w, k) for j in index.get(d, ())):
            out.append(i)
    return out


def build_model(out, budget, min_count, workers):
    import numpy as np
    from multiprocessing import Pool

    from word_predictor.model import write_model
    from word_predictor.text import SPECIALS

    paths = sorted(CORPUS.glob("*.train.jsonl"))
    if not paths:
        sys.exit("No corpus found; run: uv run training/build.py fetch")
    t0 = time.time()
    tok, inner, cased = Counter(), Counter(), Counter()
    with Pool(workers) as pool:
        for a, b, c in pool.imap_unordered(_count_chunk, _chunks(paths)):
            tok.update(a)
            inner.update(b)
            cased.update(c)
    n_tokens = sum(tok.values())
    cands = [(c, w) for w, c in tok.items()
             if w not in SPECIALS and c >= MIN_WORD_COUNT and len(w) <= MAX_WORD_LEN]
    words = sorted(w for _, w in sorted(cands, reverse=True)[:MAX_VOCAB])
    W, V = len(words), len(words) + len(SPECIALS)
    tid = {w: i for i, w in enumerate(words)}
    for i, t in enumerate(SPECIALS):
        tid[t] = W + i
    covered = sum(tok[w] for w in words)
    all_words = sum(c for w, c in tok.items() if w not in SPECIALS)
    print(f"Pass 1: {n_tokens:,} tokens, vocabulary of {W:,} words ({covered / all_words:.2%} of word occurrences), "
          f"{time.time() - t0:.0f} s")

    seqs, valids = [], []
    with Pool(workers, initializer=_init_ids, initargs=(tid,)) as pool:
        for s, v in pool.imap(_ids_chunk, _chunks(paths)):
            seqs.append(np.frombuffer(s, dtype=np.uint16))
            valids.append(np.frombuffer(v, dtype=np.uint8))
    seq = np.concatenate(seqs).astype(np.int64)
    pos = np.flatnonzero(np.concatenate(valids))
    del seqs, valids
    u, v, w = seq[pos - 2], seq[pos - 1], seq[pos]
    del seq, pos
    print(f"Pass 2: {len(w):,} trigrams, {time.time() - t0:.0f} s")

    is_word = np.zeros(V, dtype=bool)
    is_word[:W] = True
    k3, c3 = np.unique((u * V + v) * V + w, return_counts=True)
    k2raw, craw2 = np.unique(v * V + w, return_counts=True)
    del u, v, w
    cont1 = np.bincount(k2raw % V, minlength=V).astype(np.float64)
    p1 = np.zeros(V)
    p1[:W] = cont1[:W] / cont1.sum()
    kc2, cc2 = np.unique(k3 % (V * V), return_counts=True)
    assert np.array_equal(kc2, k2raw)  # every bigram has a preceding token (segments start with padding <s>)
    del k2raw
    print(f"Counts: {len(k3):,} distinct trigrams, {len(kc2):,} distinct bigrams, {time.time() - t0:.0f} s")

    vocab_blob = "\n".join(words)
    forms = []
    for orig, n in cased.items():
        low = orig.lower()
        if low in tid and tid[low] < W and n >= CASE_SHARE * inner[low]:
            forms.append((tid[low], orig))
    i_id = {tid[x]: "I" + x[1:] for x in words if x == "i" or x.startswith("i'")}
    forms = dict(forms) | i_id
    case_blob = "".join(f"{i}\t{f}\n" for i, f in sorted(forms.items()))
    blocked = sorted(tid[x] for x in load_blocklist() if x in tid and tid[x] < W)
    misspelled = misspellings(words, tok, set(forms), load_dictionary())
    print(f"Spelling: {len(misspelled):,} likely misspellings will not be suggested, {time.time() - t0:.0f} s")

    # Pruning: score every entry by weighted difference and pick one threshold theta so the file just fits the budget.
    # Size: 3 bytes per entry, 9 bytes per trigram context (key, offset, backoff weight), everything else is fixed.
    s2, s3 = prune_scores(k3, c3, kc2, cc2, craw2, V, is_word, p1)
    s2[craw2 < min_count] = -np.inf
    s3[c3 < min_count] = -np.inf
    ctx3 = k3 // V
    starts = np.flatnonzero(np.r_[True, ctx3[1:] != ctx3[:-1]])
    srt2, srt3, srtc = np.sort(s2), np.sort(s3), np.sort(np.maximum.reduceat(s3, starts))
    del ctx3, starts
    at_least = lambda s, x: len(s) - int(np.searchsorted(s, x))  # noqa: E731
    fixed = (len(vocab_blob.encode()) + W + len(case_blob.encode()) + 2 * (len(blocked) + len(misspelled))
             + 5 * V + 2048)

    def size(x):
        return fixed + 3 * at_least(srt2, x) + 3 * at_least(srt3, x) + 9 * at_least(srtc, x)

    for _ in range(4):  # the estimate ignores the HEAD tables; if the export overshoots, tighten and retry
        lo, hi = 0.0, float(max(srt2[-1], srt3[-1]))
        for _ in range(60):
            mid = (lo + hi) / 2
            lo, hi = (lo, mid) if size(mid) <= budget else (mid, hi)
        theta = hi
        L2 = kn_level(kc2, cc2, V, is_word, s2 >= theta)
        L3 = kn_level(k3, c3, V, is_word, s3 >= theta)
        sections = export_sections(L2, L3, V, vocab_blob, case_blob, blocked, misspelled, quant(p1[:W]))
        total = 12 + 2048 + sum(12 + len(d) for _, d in sections.values())
        if total <= budget:
            break
        fixed += total - budget + 1024
    print(f"Pruning: threshold {theta:.2f} -> {len(L2['e_w']):,} bigrams, {len(L3['e_w']):,} trigrams, "
          f"{time.time() - t0:.0f} s")

    meta = {
        "name": "word-predictor-en", "specials": list(SPECIALS), "words": W, "tokens": int(n_tokens),
        "prune": {"method": "weighted-difference", "theta": round(theta, 3), "min_count": min_count},
        "discounts": {"bigram": L2["D"], "trigram": L3["D"]},
        "sources": [p.name.split(".")[0] for p in paths], "license": "ODC-By-1.0", "built": time.strftime("%Y-%m-%d"),
    }
    write_model(out, meta, sections)
    print(f"Wrote {out}: {out.stat().st_size / 1e6:.2f} MB ({len(forms):,} cased forms, "
          f"{len(blocked)} blocked words, {len(misspelled):,} misspellings), {time.time() - t0:.0f} s total")


def export_sections(L2, L3, V, vocab_blob, case_blob, blocked, misspelled, unigram):
    import numpy as np

    b_off = np.searchsorted(L2["e_ctx"], np.arange(V + 1)).astype("<u4")
    b_gam = np.zeros(V, dtype=np.uint8)
    b_gam[L2["ctx"]] = quant(L2["gamma"])
    t_keys, t_start = np.unique(L3["e_ctx"], return_index=True)
    t_off = np.append(t_start, len(L3["e_ctx"])).astype("<u4")
    t_gam = quant(L3["gamma"][np.searchsorted(L3["ctx"], t_keys)])
    t_index = {int(k): j for j, k in enumerate(t_keys)}
    b_hk, b_hp = heads(L2["e_ctx"], L2["e_p"], lambda k: k)
    t_hk, t_hp = heads(L3["e_ctx"], L3["e_p"], t_index.__getitem__)
    return {
        "VOCB": ("s", vocab_blob.encode()), "CASE": ("s", case_blob.encode()),
        "UNIG": ("B", unigram.tobytes()), "BLCK": ("H", np.array(blocked, dtype="<u2").tobytes()),
        "MISS": ("H", np.array(misspelled, dtype="<u2").tobytes()),
        "B2OF": ("I", b_off.tobytes()), "B2GA": ("B", b_gam.tobytes()),
        "B2ID": ("H", L2["e_w"].astype("<u2").tobytes()), "B2PR": ("B", quant(L2["e_p"]).tobytes()),
        "T3KY": ("I", t_keys.astype("<u4").tobytes()), "T3OF": ("I", t_off.tobytes()),
        "T3GA": ("B", t_gam.tobytes()),
        "T3ID": ("H", L3["e_w"].astype("<u2").tobytes()), "T3PR": ("B", quant(L3["e_p"]).tobytes()),
        "B2HK": ("I", b_hk.tobytes()), "B2HP": ("I", b_hp.tobytes()),
        "T3HK": ("I", t_hk.tobytes()), "T3HP": ("I", t_hp.tobytes()),
    }


