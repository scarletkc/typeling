def _texts(paths):
    for p in paths:
        with open(p, encoding="utf-8") as f:
            for line in f:
                yield json.loads(line)["text"]


def _chunks(paths, size=5000):
    batch = []
    for t in _texts(paths):
        batch.append(t)
        if len(batch) == size:
            yield batch
            batch = []
    if batch:
        yield batch


def _count_chunk(texts):
    """Pass 1: token counts, plus the non-sentence-initial counts of each word and of its cased forms,
    used to restore casing."""
    from word_predictor.text import BOUNDARY, PUNCT, tokenize

    tok, inner, cased = Counter(), Counter(), Counter()
    for text in texts:
        prev = BOUNDARY
        for t, orig in tokenize(text):
            tok[t] += 1
            if orig is not None and prev != BOUNDARY and prev != PUNCT:
                inner[t] += 1
                if orig != t:
                    cased[orig] += 1
            prev = t
    return tok, inner, cased


def _init_ids(tid):
    _TID.update(tid)


def _ids_chunk(texts):
    """Pass 2: each segment becomes ids [<s>, <s>, tokens..., <s>]; `valid` marks the positions to predict."""
    from array import array

    from word_predictor.text import BOUNDARY, UNK, tokenize

    s, unk, tid = _TID[BOUNDARY], _TID[UNK], _TID
    seq, valid = array("H"), bytearray()
    for text in texts:
        ids = [tid.get(t, unk) for t, _ in tokenize(text)]
        if ids and ids[0] == s:
            ids = ids[1:]
        if not ids:
            continue
        if ids[-1] != s:
            ids.append(s)
        seq.extend((s, s))
        seq.extend(ids)
        valid.extend(b"\0\0" + b"\1" * len(ids))
    return seq.tobytes(), bytes(valid)


def kn_level(keys, counts, V, is_word, keep=None):
    """One level of interpolated modified Kneser-Ney (Chen & Goodman's three discounts).
    keys = context * V + word, sorted ascending. Only entries whose next token is a word are stored; `keep`
    selects which of them to retain (default: all), and the mass of pruned entries goes to the backoff weight."""
    import numpy as np

    n1, n2, n3, n4 = (int((counts == k).sum()) for k in (1, 2, 3, 4))
    y = n1 / (n1 + 2 * n2)
    D = np.array([0.0, 1 - 2 * y * n2 / n1, 2 - 3 * y * n3 / n2, 3 - 4 * y * n4 / n3])
    disc = D[np.minimum(counts, 3)]
    ctx, w = keys // V, keys % V
    uctx, inv = np.unique(ctx, return_inverse=True)
    tot = np.bincount(inv, weights=counts).astype(np.float64)
    word = is_word[w]
    keep = word if keep is None else word & keep
    pruned = word & ~keep
    back = np.bincount(inv, weights=disc, minlength=len(uctx))
    back += np.bincount(inv[pruned], weights=counts[pruned] - disc[pruned], minlength=len(uctx))
    gamma = back / tot
    return dict(ctx=uctx, gamma=gamma, e_ctx=ctx[keep], e_w=w[keep], e_gamma=gamma[inv[keep]],
                e_p=(counts[keep] - disc[keep]) / tot[inv[keep]], D=D[1:].round(3).tolist())


def prune_scores(k3, c3, kc2, cc2, craw2, V, is_word, p1):
    """Seymore & Rosenfeld weighted difference: the cost of removing an entry is approximately
    its training count * ln(interpolated probability / backoff-only probability).
    Returns (bigram scores, trigram scores) aligned with kc2 and k3; entries whose next token is not a word
    score -inf."""
    import numpy as np

    L2 = kn_level(kc2, cc2, V, is_word)
    G2 = np.ones(V)
    G2[L2["ctx"]] = L2["gamma"]
    w2 = is_word[kc2 % V]
    s2 = np.full(len(kc2), -np.inf)
    s2[w2] = craw2[w2] * np.log1p(L2["e_p"] / (L2["e_gamma"] * p1[L2["e_w"]]))
    L3 = kn_level(k3, c3, V, is_word)
    v3 = L3["e_ctx"] % V
    j = np.searchsorted(L2["e_ctx"] * V + L2["e_w"], v3 * V + L3["e_w"])
    lower = L2["e_p"][j] + G2[v3] * p1[L3["e_w"]]
    w3 = is_word[k3 % V]
    s3 = np.full(len(k3), -np.inf)
    s3[w3] = c3[w3] * np.log1p(L3["e_p"] / (L3["e_gamma"] * lower))
    return s2, s3


def quant(p):
    import numpy as np

    from word_predictor.model import STEP

    return np.clip(np.rint(-np.log(np.maximum(p, 1e-300)) / STEP), 0, 255).astype(np.uint8)


def heads(e_ctx, e_p, key_of):
    """Positions of the HEAD most probable entries of every context with more than HEAD_MIN entries.
    key_of(context) -> the key the runtime uses to look up that context."""
    import numpy as np

    from word_predictor.model import HEAD, HEAD_MIN

    keys, pos = [], []
    uniq, start, cnt = np.unique(e_ctx, return_index=True, return_counts=True)
    for k, a, n in zip(uniq, start, cnt):
        if n > HEAD_MIN:
            top = a + np.argsort(-e_p[a:a + n], kind="stable")[:HEAD]
            keys.append(key_of(int(k)))
            pos.extend(top.tolist())
    return np.array(keys, dtype="<u4"), np.array(pos, dtype="<u4")


