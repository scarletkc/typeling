# --- Fetching ---

_local = threading.local()


def _fs():
    if not hasattr(_local, "fs"):
        from huggingface_hub import HfFileSystem

        _local.fs = HfFileSystem()
    return _local.fs


def row_group_count(path):
    import pyarrow.parquet as pq

    with _fs().open(path) as f:
        return pq.ParquetFile(f).metadata.num_row_groups


def read_row_group(path, i, columns):
    import pyarrow.parquet as pq

    for attempt in range(5):
        try:
            with _fs().open(path) as f:
                return pq.ParquetFile(f).read_row_group(i, columns=columns)
        except Exception as e:  # transient network errors
            if attempt == 4:
                raise
            print(f"  retrying {path} row group {i}: {e}", file=sys.stderr)
            time.sleep(3 * (attempt + 1))


def read_all(path, columns):
    import pyarrow as pa

    return pa.concat_tables(read_many([(path, i) for i in range(row_group_count(path))], columns))


FETCH_WORKERS = 24


def read_many(tasks, columns):
    """Read (file, row group) pairs in parallel and yield the pyarrow tables in order.
    Only a bounded window is in flight, so a consumer that stops early does not download the rest."""
    with ThreadPoolExecutor(FETCH_WORKERS) as pool:
        pending = deque()
        try:
            for path, i in tasks:
                pending.append(pool.submit(read_row_group, path, i, columns))
                if len(pending) >= 2 * FETCH_WORKERS:
                    yield pending.popleft().result()
            while pending:
                yield pending.popleft().result()
        finally:
            for f in pending:
                f.cancel()


# --- Cleaning ---


def split_of(key, test_share=10):
    b = int(hashlib.md5(key.encode("utf-8")).hexdigest()[:8], 16) % 1000
    return "dev" if b < test_share else "test" if b < 2 * test_share else "train"


def scrub(text):
    """Writing sources: remove emails, URLs and phone numbers."""
    return PHONE.sub(" ", URL.sub(" ", EMAIL.sub(" ", text)))


def typed_ok(text, max_words=100):
    """Chat sources: accept text that looks typed by a person, not pasted code, tables or long documents,
    and that contains no emails, URLs or phone numbers."""
    if EMAIL.search(text) or URL.search(text) or PHONE.search(text) or CODE.search(text):
        return False
    n = len(text.split())
    if n < 2 or n > max_words or text.count("\n") > 3:
        return False
    if sum(ord(c) > 127 for c in text) > 0.02 * len(text):
        return False
    letters = sum(c.isalpha() for c in text)
    return letters >= 0.75 * sum(not c.isspace() for c in text)


class Sink:
    """Writes the segments of one source to data/corpus/<source>.<train|dev|test>.jsonl
    (written as .tmp files and renamed only once the source is complete)."""

    def __init__(self, name):
        self.name = name
        self.paths = {s: CORPUS / f"{name}.{s}.jsonl" for s in SPLITS}
        self.files = {s: open(str(p) + ".tmp", "w", encoding="utf-8", newline="\n") for s, p in self.paths.items()}
        self.segs, self.words = Counter(), Counter()

    def done(self):
        return all(p.exists() for p in self.paths.values())

    def write(self, split, text):
        self.files[split].write(json.dumps({"text": text}, ensure_ascii=False) + "\n")
        self.segs[split] += 1
        self.words[split] += len(text.split())

    def close(self):
        for s, f in self.files.items():
            f.close()
            Path(str(self.paths[s]) + ".tmp").replace(self.paths[s])
        print(f"  {self.name}: " + "  ".join(f"{s} {self.segs[s]:,} segments {self.words[s]:,} words" for s in SPLITS))


def fetch_fineweb(sink):
    path = "datasets/HuggingFaceFW/fineweb/sample/10BT/000_00000.parquet"
    rgs = list(range(0, row_group_count(path), 25))
    for table in read_many([(path, i) for i in rgs], ["id", "text"]):
        for doc_id, text in zip(table.column("id").to_pylist(), table.column("text").to_pylist()):
            text = scrub(normalize(text))
            if len(text) > 12000:  # keep only the start of long documents to cover more of them
                text = text[: text.rfind("\n", 0, 12000) if "\n" in text[:12000] else 12000]
            sink.write(split_of(doc_id), text)


def fetch_soda(sink):
    base = "datasets/allenai/soda/"
    for name, split, take in (("train.parquet", "train", slice(None, None, 9)),
                              ("valid.parquet", "dev", slice(0, 400)),
                              ("test.parquet", "test", slice(0, 400))):
        dialogues = read_all(base + name, ["dialogue"]).column("dialogue").to_pylist()
        for dialogue in dialogues[take]:
            for turn in dialogue:
                sink.write(split, normalize(turn).strip())


WILDCHAT_TRAIN_WORDS = 7_500_000


def fetch_wildchat(sink):
    files = [f"datasets/allenai/WildChat-1M/data/train-{i:05d}-of-00014.parquet" for i in range(14)]
    tasks = [(f, i) for f in files for i in range(row_group_count(f))]
    cols = ["language", "toxic", "redacted"] + [f"conversation.list.element.{c}" for c in
                                                ("role", "content", "language", "toxic", "redacted")]
    seen = set()
    for n, table in enumerate(read_many(tasks, cols)):
        if sink.words["train"] >= WILDCHAT_TRAIN_WORDS:
            break
        for conv, lang, toxic, redacted in zip(*(table.column(c).to_pylist() for c in
                                                 ("conversation", "language", "toxic", "redacted"))):
            if lang != "English" or toxic or redacted:
                continue
            for turn in conv:
                if turn["role"] != "user" or turn["language"] != "English" or turn["toxic"] or turn["redacted"]:
                    continue
                text = normalize(turn["content"]).strip()
                key = " ".join(text.lower().split())
                if key in seen or not typed_ok(text):
                    continue
                seen.add(key)
                sink.write(split_of(key), text)
        if n % 100 == 99:
            print(f"    wildchat {n + 1}/{len(tasks)} row groups", file=sys.stderr)


def fetch_oasst2(sink):
    base = "datasets/OpenAssistant/oasst2/data/"
    for name in ("train-00000-of-00001-88ba0162028a73fc.parquet", "validation-00000-of-00001-1deeef95c3248fe0.parquet"):
        t = read_all(base + name, ["message_id", "text", "role", "lang", "deleted", "synthetic"])
        for mid, text, role, lang, deleted, synthetic in zip(*(t.column(c).to_pylist() for c in t.column_names)):
            if lang != "en" or role != "prompter" or deleted or synthetic:
                continue
            text = normalize(text).strip()
            if typed_ok(text):
                split = "train" if name.startswith("train") else ("dev" if split_of(mid, 500) == "dev" else "test")
                sink.write(split, text)


IRC_LINE = re.compile(r"^\[\d\d:\d\d\] <[^>]+> (.+)$", re.M)
IRC_ADDRESS = re.compile(r"^(\S+?)[:,]\s+")
IRC_TECH = re.compile(r"/|\bsudo\b|\bapt(?:-get)?\b|\.deb\b|\bdpkg\b|\bgrep\b|\bchmod\b|\bppa\b", re.I)
IRC_SKIP = ("devel", "meeting", "bugs")
IRC_WORDS_PER_FILE = 1_500_000


def fetch_irc(sink):
    """Ubuntu IRC logs: one segment per message, with a leading "nick:" address removed. Messages that look
    like commands, paths or code are dropped, and so are development, meeting and bug-triage channels."""
    seen = set()
    for i in range(3):
        start = sum(sink.words.values())
        path = f"datasets/common-pile/ubuntu_irc_filtered/ubuntu-chat-dolma-{i:04d}.json.gz"
        with _fs().open(path, block_size=8 << 20) as f, gzip.open(f, "rt", encoding="utf-8") as g:
            for line in g:
                doc = json.loads(line)
                meta = doc["metadata"]
                if any(k in meta["channel"] for k in IRC_SKIP):
                    continue
                nicks = set(meta["authors"])
                for m in IRC_LINE.finditer(doc["text"]):
                    msg = normalize(m.group(1)).strip()
                    a = IRC_ADDRESS.match(msg)
                    if a and a.group(1) in nicks:
                        msg = msg[a.end():]
                    key = " ".join(msg.lower().split())
                    if key in seen or IRC_TECH.search(msg) or not typed_ok(msg, 60):
                        continue
                    seen.add(key)
                    sink.write(split_of(key), msg)
                if sum(sink.words.values()) - start >= IRC_WORDS_PER_FILE:
                    break


SOURCES = {"oasst2": fetch_oasst2, "soda": fetch_soda, "fineweb": fetch_fineweb, "wildchat": fetch_wildchat,
           "irc": fetch_irc}


def fetch(names):
    CORPUS.mkdir(parents=True, exist_ok=True)
    for name in names:
        if all((CORPUS / f"{name}.{s}.jsonl").exists() for s in SPLITS):
            print(f"  {name}: already fetched, skipping")
            continue
        t0 = time.time()
        print(f"Fetching {name}...")
        sink = Sink(name)
        SOURCES[name](sink)
        sink.close()
        print(f"  done in {time.time() - t0:.0f} s")


